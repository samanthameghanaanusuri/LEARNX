m6_lesson = """# SQL Querying

## WHAT IS IT?
SQL Querying is the process of retrieving data from a database using the `SELECT` statement. It allows you to filter, sort, group, and perform calculations on data before it is returned to the user or application.

## WHY DO WE NEED IT?
Storing data is useless if you cannot retrieve it effectively. Without advanced querying, you would have to pull the entire database into your application's memory and write complex code (like loops in Python/Java) to filter the data. The DBMS is highly optimized to do this much faster.

## WHERE IS IT USED?
1. **Reporting Dashboards:** Querying total sales for the last 30 days to display on a chart.
2. **Search Functions:** When a user types a product name in an e-commerce store, a query with the `LIKE` operator fetches matching products.

## HOW DOES IT WORK?
A basic query specifies *what* columns to return (`SELECT`) and *where* to get them (`FROM`). You can add conditions (`WHERE`), sort the results (`ORDER BY`), and limit the number of rows returned (`LIMIT`). The DBMS query optimizer automatically decides the fastest way to execute this.

## TERMINOLOGY
- **SELECT:** The keyword used to specify which columns to retrieve.
- **WHERE:** The clause used to filter rows based on conditions.
- **ORDER BY:** Sorts the result set by one or more columns (ASC or DESC).
- **GROUP BY:** Groups rows that have the same values into summary rows.
- **HAVING:** Used instead of WHERE for filtering grouped records.
- **Alias (AS):** Temporarily renaming a column or table for readability.

## VISUAL / DIAGRAM
```text
Table: Products
+----+--------+-------+
| ID | Name   | Price |
+----+--------+-------+
| 1  | Apple  | 1.00  |
| 2  | Banana | 0.50  |
| 3  | Cherry | 2.00  |
+----+--------+-------+

Query: SELECT Name FROM Products WHERE Price < 1.50;

Result:
+--------+
| Name   |
+--------+
| Apple  |
| Banana |
+--------+
```

## SYNTAX
```sql
SELECT column1, column2 AS alias_name
FROM table_name
WHERE condition
ORDER BY column1 DESC
LIMIT 10;
```

## SIMPLE EXAMPLE
Imagine looking for employees who make more than $50,000 and sorting them by salary from highest to lowest.

```sql
SELECT name, salary 
FROM employees 
WHERE salary > 50000 
ORDER BY salary DESC;
```

## LINE-BY-LINE EXPLANATION
- `SELECT name, salary`: We only want these two columns, not the whole table.
- `FROM employees`: We are reading from the employees table.
- `WHERE salary > 50000`: We filter out anyone making $50k or less.
- `ORDER BY salary DESC`: We sort the results in descending order.

## REAL-WORLD EXAMPLE
An admin wants to know the total revenue generated by each department.
```sql
SELECT department_id, SUM(salary) AS total_payroll
FROM employees
GROUP BY department_id
HAVING SUM(salary) > 1000000;
```
This queries the total payroll, groups it per department, and only shows departments with over a million in payroll.

## OUTPUT
```text
+---------------+---------------+
| department_id | total_payroll |
+---------------+---------------+
| 3             | 1500000.00    |
+---------------+---------------+
```

## COMMON MISTAKES
- **Using HAVING instead of WHERE:** `WHERE` filters rows *before* grouping; `HAVING` filters groups *after* grouping.
- **Selecting un-grouped columns:** If you `GROUP BY department_id`, you cannot `SELECT name` unless name is inside an aggregate function like `MAX(name)`.
- **Inefficient wildcard searches:** Using `LIKE '%apple'` forces a full table scan because the database cannot use an index if the wildcard is at the beginning.

## BEST PRACTICES
- **Avoid SELECT *:** Always list the specific columns you need. `SELECT *` wastes network bandwidth and memory.
- **Use aliases for clarity:** If a column name is confusing or an aggregate function is used (e.g., `COUNT(*)`), give it an alias `AS total_users`.
- **Filter early:** Use `WHERE` to filter data as early as possible to reduce the workload on the database engine.

## TRY IT YOURSELF
Head to the exercises to practice writing `SELECT` queries with filtering and grouping.
"""

m7_lesson = """# Joins & Subqueries

## WHAT IS IT?
A **JOIN** is a SQL operation that combines rows from two or more tables based on a related column between them. A **Subquery** (or inner query) is a query nested inside another SQL query.

## WHY DO WE NEED IT?
Because of normalization, data is spread across multiple tables to prevent redundancy. To get a complete picture (e.g., seeing a Student's Name and their Course Name), you must connect the `Students` table and the `Courses` table. Joins and subqueries allow you to piece this fragmented data back together dynamically.

## WHERE IS IT USED?
1. **Generating Invoices:** Joining the `Customers`, `Orders`, and `Products` tables to create a complete bill.
2. **Complex Filtering:** Using a subquery to find all employees who earn more than the average salary.

## HOW DOES IT WORK?
- **INNER JOIN:** Returns records that have matching values in both tables.
- **LEFT JOIN:** Returns all records from the left table, and the matched records from the right table (unmatched rows show NULL).
- **RIGHT JOIN:** Returns all records from the right table, and the matched records from the left.
- **FULL OUTER JOIN:** Returns all records when there is a match in either left or right table.

## TERMINOLOGY
- **Join Condition:** The rule defining how tables connect (usually `ON table1.id = table2.id`).
- **Cartesian Product (CROSS JOIN):** Every row in Table A combined with every row in Table B. Rarely useful, usually a mistake.
- **Correlated Subquery:** A subquery that depends on values from the outer query, meaning it runs once for every row in the outer query.

## VISUAL / DIAGRAM
```text
Table A (Students)       Table B (Enrollments)
1: Alice (Course: 10)    10: Math
2: Bob   (Course: 20)    20: Science
3: Ravi  (Course: NULL)  30: History

INNER JOIN (Matches only)
Alice -> Math
Bob   -> Science

LEFT JOIN (All Students, matched enrollments)
Alice -> Math
Bob   -> Science
Ravi  -> NULL
```

## SYNTAX
```sql
SELECT A.name, B.course_name
FROM Students A
INNER JOIN Enrollments B
ON A.course_id = B.course_id;
```

## SIMPLE EXAMPLE
Find all products whose price is greater than the average price. You need a subquery because you don't know the average price beforehand.

```sql
SELECT name, price 
FROM Products 
WHERE price > (SELECT AVG(price) FROM Products);
```

## LINE-BY-LINE EXPLANATION
- `(SELECT AVG(price) FROM Products)`: The database executes this inner subquery first. Let's say it calculates `$15.00`.
- `WHERE price > 15.00`: The outer query then uses that result to filter the main table.

## REAL-WORLD EXAMPLE
In a hospital system, finding all patients who were treated by a specific doctor:
```sql
SELECT p.first_name, p.last_name, d.last_name AS doctor_name
FROM Patients p
INNER JOIN Appointments a ON p.patient_id = a.patient_id
INNER JOIN Doctors d ON a.doctor_id = d.doctor_id
WHERE d.last_name = 'Smith';
```

## OUTPUT
```text
+------------+-----------+-------------+
| first_name | last_name | doctor_name |
+------------+-----------+-------------+
| John       | Doe       | Smith       |
+------------+-----------+-------------+
```

## COMMON MISTAKES
- **Forgetting the ON clause:** Doing a `JOIN` without `ON` results in a Cross Join, returning massive amounts of useless data (e.g., 1,000 users joined with 1,000 orders = 1,000,000 rows).
- **Ambiguous Column Names:** If both tables have an `id` column, you must specify which one you want (e.g., `Users.id` or `Orders.id`).
- **Overusing Correlated Subqueries:** They can be extremely slow because they execute the inner query for every single row in the outer query. Often, a JOIN is faster.

## BEST PRACTICES
- **Use table aliases:** Instead of `Customers.customer_name`, use `c.customer_name` by defining `Customers c` in the FROM clause.
- **Prefer JOINs over Subqueries:** Modern query optimizers are very good at handling JOINs efficiently. Subqueries (especially correlated ones) can cause performance bottlenecks.
- **Be careful with LEFT JOIN:** Understand that it will introduce NULL values into your result set if there is no match.

## TRY IT YOURSELF
Go to the exercises to practice writing JOINs and nested subqueries.
"""

m8_lesson = """# Constraints, Keys & Normalization

## WHAT IS IT?
**Constraints** are strict rules applied to database columns to prevent invalid data from being inserted. **Normalization** is the systematic process of organizing tables to eliminate data redundancy and ensure data dependencies make sense.

## WHY DO WE NEED IT?
Without constraints, someone could enter a negative age, a duplicate username, or an invalid department ID. Without normalization, a database becomes bloated with duplicate data (e.g., storing a customer's address 50 times for 50 orders), making updates a nightmare (Update Anomalies).

## WHERE IS IT USED?
1. **User Registration:** Using a `UNIQUE` constraint on the email column so no two users can share the same email.
2. **Database Design Phase:** Applying normalization rules (1NF, 2NF, 3NF) before writing any SQL to ensure the architecture is sound.

## HOW DOES IT WORK?
You apply constraints during table creation. Normalization works in stages (Normal Forms):
- **1NF (First Normal Form):** Ensure every column holds an atomic (indivisible) value. No lists/arrays in a single cell.
- **2NF (Second Normal Form):** Meet 1NF, and ensure no non-key attribute depends on only a *part* of a composite primary key.
- **3NF (Third Normal Form):** Meet 2NF, and ensure no non-key attribute depends on another non-key attribute (No Transitive Dependency).

## TERMINOLOGY
- **NOT NULL:** Ensures a column cannot have a NULL value.
- **UNIQUE:** Ensures all values in a column are different.
- **CHECK:** Ensures values satisfy a specific condition (e.g., `age >= 18`).
- **DEFAULT:** Sets a default value if none is specified.
- **Functional Dependency:** When the value of attribute A uniquely determines the value of attribute B (A -> B).

## VISUAL / DIAGRAM
Unnormalized Table (Violates 1NF due to multiple values in 'Courses'):
```text
ID | Name  | Courses
1  | Alice | Math, Science
```
Normalized to 1NF (Atomic values):
```text
ID | Name  | Course
1  | Alice | Math
1  | Alice | Science
```

## SYNTAX
```sql
CREATE TABLE Users (
    id INT PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    age INT CHECK (age >= 18),
    status VARCHAR(20) DEFAULT 'Active'
);
```

## SIMPLE EXAMPLE
Imagine an `Orders` table storing `Customer_Name`, `Customer_Address`, and `Total_Amount`. If a customer moves, you must update 100 past orders. 
**Normalization fix (3NF):** Move `Customer_Name` and `Customer_Address` into a separate `Customers` table. The `Orders` table only keeps a `Customer_ID`.

## LINE-BY-LINE EXPLANATION
- `username VARCHAR(50) UNIQUE NOT NULL`: The database will reject the INSERT if the username already exists (`UNIQUE`) or if it's left blank (`NOT NULL`).
- `age INT CHECK (age >= 18)`: The database evaluates this rule before inserting. If age is 17, it throws an error.

## REAL-WORLD EXAMPLE
A retail company stores `ZipCode` and `CityName` in the `Employees` table. This violates 3NF because `CityName` depends on `ZipCode`, not the Employee's Primary Key. If the post office renames a city, they must update thousands of employee records. Moving it to a `Locations` table fixes this.

## OUTPUT
```text
ERROR: new row for relation "Users" violates check constraint "Users_age_check"
```

## COMMON MISTAKES
- **Over-normalization:** Normalizing a database to 5NF can result in needing 15 JOINs to answer a simple query, tanking performance. Sometimes, intentional denormalization is necessary for speed.
- **Ignoring Constraints:** Relying entirely on application code (like JavaScript or Python) to validate data. If a bug occurs in the app, garbage data enters the DB.
- **Primary Key mutations:** Attempting to update a Primary Key value. PKs should ideally be immutable (unchanging).

## BEST PRACTICES
- **Enforce rules at the database level:** Always use `NOT NULL`, `UNIQUE`, and `CHECK` constraints to protect data integrity.
- **Aim for 3NF:** For most OLTP (Online Transaction Processing) systems, achieving Third Normal Form is the sweet spot between integrity and performance.
- **Use Default values:** This simplifies application code and ensures required fields have sensible fallbacks.

## TRY IT YOURSELF
Proceed to the exercises to identify normalization violations and write tables with strict constraints.
"""

m9_lesson = """# Transactions & ACID

## WHAT IS IT?
A **Transaction** is a logical unit of work that contains one or more SQL statements. A transaction must be treated as an indivisible operation—either all statements execute successfully, or none of them do. This reliability is guaranteed by the **ACID** properties.

## WHY DO WE NEED IT?
Without transactions, partial failures would corrupt data. Imagine transferring $100. Step 1: Deduct $100 from Account A. Step 2: Add $100 to Account B. If the server crashes after Step 1, $100 vanishes into thin air. Transactions prevent this by rolling back Step 1 if Step 2 fails.

## WHERE IS IT USED?
1. **Banking and Finance:** Processing transfers, payments, and ledger entries.
2. **Inventory Management:** Deducting stock only if the payment processes successfully.

## HOW DOES IT WORK?
You start a transaction (`BEGIN`). You run your queries. If everything is correct, you save the changes permanently (`COMMIT`). If an error occurs, you undo everything back to the starting point (`ROLLBACK`). The database engine uses logs (Write-Ahead Logging) to ensure it can recover data even if the power cord is pulled out.

## TERMINOLOGY
- **Atomicity:** "All or nothing." The transaction fully completes or fully fails.
- **Consistency:** The transaction takes the database from one valid state to another, respecting all constraints.
- **Isolation:** Concurrent transactions do not interfere with each other. They behave as if they ran sequentially.
- **Durability:** Once committed, changes are permanent and survive system crashes.

## VISUAL / DIAGRAM
```text
      [ BEGIN TRANSACTION ]
               |
         Deduct $100 from A  --- (Success)
               |
         Add $100 to B       --- (CRASH/FAILURE!)
               |
      [ ROLLBACK TRIGGERED ] 
               |
    (A gets its $100 back. DB is safe.)
```

## SYNTAX
```sql
BEGIN; -- or START TRANSACTION;

UPDATE accounts SET balance = balance - 100 WHERE name = 'Alice';
UPDATE accounts SET balance = balance + 100 WHERE name = 'Bob';

COMMIT; -- Save changes
-- OR
ROLLBACK; -- Undo changes
```

## SIMPLE EXAMPLE
Purchasing a ticket. You need to 1) Mark the seat as taken, and 2) Charge the credit card. These two actions are grouped in a transaction. If the credit card declines, the transaction rolls back, and the seat becomes available again instantly.

## LINE-BY-LINE EXPLANATION
- `BEGIN;`: Tells the DBMS to suspend auto-committing. All subsequent queries are kept in a temporary state.
- `UPDATE ...`: The changes are made in memory but are hidden from other users.
- `COMMIT;`: The changes are permanently written to disk and made visible to everyone.

## REAL-WORLD EXAMPLE
In PostgreSQL, DDL commands (like `CREATE TABLE`) are also transactional. You can start a transaction, drop 5 tables, realize you made a mistake, and issue a `ROLLBACK` to restore them instantly. (Note: MySQL does not support transactional DDL).

## OUTPUT
```text
BEGIN
UPDATE 1
UPDATE 1
COMMIT
```

## COMMON MISTAKES
- **Forgetting to COMMIT:** Leaving a transaction hanging open locks rows in the database, causing other users' queries to freeze (wait) indefinitely.
- **Gigantic transactions:** Wrapping a million `INSERT` statements in a single transaction. If one fails, you lose hours of work, and it consumes massive amounts of RAM.
- **Not handling errors in application code:** If a query fails, the app must explicitly catch the error and issue the `ROLLBACK` command.

## BEST PRACTICES
- **Keep transactions short:** Retrieve necessary data beforehand, start the transaction, execute the updates, and commit immediately to release locks.
- **Use transactions for multi-table writes:** Any time an action requires updating more than one table, it must be in a transaction.
- **Rely on the DBMS:** Don't try to build "undo" logic in your application code. Let the ACID properties of the DBMS do the heavy lifting.

## TRY IT YOURSELF
Go to the exercises to identify ACID properties and simulate transaction failures.
"""

m10_lesson = """# Concurrency Control

## WHAT IS IT?
**Concurrency Control** is the mechanism managed by the DBMS to ensure that multiple transactions can execute simultaneously without violating data integrity. It strictly enforces the 'Isolation' property of ACID.

## WHY DO WE NEED IT?
In the real world, databases don't process one user at a time. Amazon processes thousands of orders per second. If two users try to buy the last concert ticket at the exact same millisecond, the database must safely handle the collision so that the ticket isn't sold twice.

## WHERE IS IT USED?
1. **Ticket Booking Systems:** Preventing double-booking of airline or cinema seats.
2. **Stock Trading Platforms:** Ensuring high-frequency trades are processed accurately without overwriting each other.

## HOW DOES IT WORK?
The DBMS uses **Locks**. Before a transaction updates a row, it acquires an Exclusive Lock. If another transaction wants to update that same row, it must wait in a queue until the first transaction commits and releases the lock. 

## TERMINOLOGY
- **Lost Update:** Transaction B overwrites Transaction A's update before A commits.
- **Dirty Read:** Reading data that has been modified by an uncommitted transaction (which might later roll back).
- **Shared Lock (Read Lock):** Multiple transactions can read the data, but none can write.
- **Exclusive Lock (Write Lock):** Only one transaction can access the data. No one else can read or write.
- **Deadlock:** Transaction A is waiting for a lock held by B, and B is waiting for a lock held by A. They are stuck forever.

## VISUAL / DIAGRAM
The Lost Update Problem (Without Concurrency Control):
```text
Time  | Transaction 1 (T1)       | Transaction 2 (T2)
-------------------------------------------------------
 1    | Read Ticket Count (1)    | 
 2    |                          | Read Ticket Count (1)
 3    | Update Count (1-1=0)     | 
 4    |                          | Update Count (1-1=0)
 5    | Commit                   | 
 6    |                          | Commit
```
Result: Both users got a confirmation, but only 1 ticket existed! (Double selling).

## SYNTAX
Concurrency is mostly handled automatically based on the **Isolation Level**, but you can manually lock rows using `FOR UPDATE`.
```sql
BEGIN;

SELECT * FROM tickets 
WHERE seat_id = 'A1' 
FOR UPDATE; -- Acquires an Exclusive Lock immediately

UPDATE tickets SET status = 'sold' WHERE seat_id = 'A1';

COMMIT; -- Lock released
```

## SIMPLE EXAMPLE
Imagine a shared bank account. Husband checks balance ($100) at ATM A. Wife checks balance ($100) at ATM B. Husband withdraws $100. Wife withdraws $100. Concurrency control locks the row when the Husband starts, forcing the Wife's ATM to wait. Once the Husband finishes (balance = $0), the Wife's ATM proceeds, sees $0, and rejects her withdrawal.

## LINE-BY-LINE EXPLANATION
- `FOR UPDATE`: This SQL clause tells the DBMS: "I am reading this row right now with the intention of updating it. Do not let anyone else read or modify this row until my transaction is complete."

## REAL-WORLD EXAMPLE
**Isolation Levels** define how strict concurrency should be.
- `READ UNCOMMITTED`: Fastest, but allows Dirty Reads. (Risky).
- `READ COMMITTED`: Default for most databases. Prevents Dirty Reads.
- `REPEATABLE READ`: Prevents Non-Repeatable reads.
- `SERIALIZABLE`: Most strict. Transactions run as if they were entirely sequential. Slowest, but perfectly safe.

## OUTPUT
```text
Query OK, 1 row affected. (Other concurrent transactions will appear to hang/wait until this commits).
```

## COMMON MISTAKES
- **Deadlocks:** Writing application code that updates tables in random orders. If App 1 updates Table A then B, and App 2 updates Table B then A, they will eventually deadlock.
- **Using Serializable unnecessarily:** Setting the whole database to Serializable isolation will cause massive performance drops and timeouts as queries constantly wait in line.
- **Ignoring Concurrency:** Testing code with a single user on localhost, pushing to production, and watching data corrupt instantly under multi-user load.

## BEST PRACTICES
- **Always update tables in the same order:** This prevents deadlocks.
- **Keep transactions extremely brief:** The less time a transaction takes, the shorter it holds a lock, increasing overall database throughput.
- **Use Optimistic Concurrency:** For web apps, instead of locking rows, add a `version` column. Update fails if the version changed since you read it. (Used heavily in modern ORMs).

## TRY IT YOURSELF
Navigate to the exercises to analyze locking scenarios, deadlocks, and isolation levels.
"""

